// services/automationService.js
//
// The TikTok auto-posting loop: pick a STEM topic students struggle with →
// generate a 1-lesson AI course on it → render that lesson to a real MP4
// (server-side, headless-Chrome via renderService.js — NOT the in-app
// "Download video" button, which only runs client-side in a real browser
// via WebCodecs and produces nothing a server-side job can reach; see the
// comment on renderService.renderLessonToFile below) → post it to TikTok
// via Buffer → delete the file. Runs on a timer (see the scheduler at the
// bottom), frequency adjustable from the admin Automation page.
//
// Nothing here spends real user credits — the Course this creates is owned
// by the admin account (found via ADMIN_EMAIL) and generated by calling
// processCourse() directly, the same core function the real /api/course
// route calls, but bypassing that route's checkCredits middleware and
// credit deduction entirely. This is an internal system job, not a paying
// user's request.

const fs = require("fs");
const path = require("path");
const User = require("../models/User");
const Course = require("../models/Course");
const AutomationPost = require("../models/AutomationPost");
const { AutomationConfig, getOrCreateAutomationConfig } = require("../models/AutomationConfig");
const { generateAutomationTopic } = require("./claudeService");
const { renderLessonToFile } = require("./renderService");
const { postVideoToTikTok } = require("./bufferService");
const { getCourseTier } = require("./pricingConfigService");

// Known, already-live production backend URL (see CLAUDE.md's deploy
// topology note) — used as the default so a fresh prod deploy works
// without needing this specific var set; override via env for local/
// staging, where Buffer couldn't reach localhost anyway.
const PUBLIC_BASE_URL = process.env.PUBLIC_BASE_URL || "https://level-up-2-dka7.onrender.com";

// Same on-disk location app.js already serves at /uploads (static, no new
// route needed — express.static serves nested subfolders on its own).
const UPLOADS_DIR =
  process.env.NODE_ENV === "production"
    ? "/data/uploads"
    : path.resolve(__dirname, "../../remotion-render/public/uploads");
const AUTOMATION_SUBDIR = "automation";

const MAX_GENERATION_WAIT_MS = 12 * 60 * 1000; // 12 min — generous over the ~5 min typical case
const POLL_INTERVAL_MS = 10_000;

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// The account every automation-generated Course is owned by, and the
// account AI-usage cost for these calls gets attributed to. Reused rather
// than a dedicated bot user — this genuinely IS "your" account doing it,
// per how this feature was asked for ("my personal automation app").
// NOTE: processCourse() unconditionally emails this user "your course is
// ready" (see courseController.js's sendCourseReadyEmail) — nothing here
// suppresses that, so expect one such email per cycle. Not touched because
// doing so means threading a new flag through a core, heavily-used
// function for a cosmetic concern on one internal caller.
async function getAutomationOwner() {
  const adminEmail = (process.env.ADMIN_EMAIL || "").toLowerCase().trim();
  if (!adminEmail) throw new Error("ADMIN_EMAIL is not set — automation has no account to own generated courses.");
  const user = await User.findOne({ email: adminEmail });
  if (!user) throw new Error(`No user found for ADMIN_EMAIL (${adminEmail}).`);
  return user;
}

// ── Stage 1: topic + caption ─────────────────────────────────────────────
async function pickTopicAndCaption() {
  const recent = await AutomationPost.find({}).sort({ createdAt: -1 }).limit(10).select("topic").lean();
  return generateAutomationTopic(recent.map((p) => p.topic));
}

// ── Stage 2: generate the 1-lesson course ────────────────────────────────
// Reuses the real "Quick Explainer" tier shape (1 lesson, its normal MCQ
// count) rather than inventing an untested 0-question path — processCourse
// always runs quiz generation regardless of mcqCount (wrapped so a quiz
// failure never fails the course), and there's no clean way to skip it
// without changing that core function. The quiz just goes unused here.
async function generateAutomationCourse(topic, ownerUserId) {
  const { processCourse } = require("../controllers/courseController"); // lazy: avoid circular require at module-load time
  const tier = await getCourseTier("quick_explainer");
  if (!tier) throw new Error('Course tier "quick_explainer" not found in PricingConfig.');

  const course = await Course.create({
    userId: ownerUserId,
    topic,
    status: "generating",
    tier: tier.key,
    tierName: tier.name,
    lessonCount: tier.lessonCount,
    mcqCount: tier.mcqCount,
    timeAllocationMinutes: tier.timeAllocationMinutes,
    creditCost: 0, // no credits spent — see module comment
    lessons: [],
    questions: [],
  });

  processCourse(
    course._id.toString(),
    topic,
    null, // pdfBuffer
    false, // isFreeTrialCourse
    null, // level
    null, // sourceFileName
    tier.lessonCount,
    tier.mcqCount,
    ownerUserId
  );

  return waitForLessonOne(course._id.toString());
}

async function waitForLessonOne(courseId) {
  const deadline = Date.now() + MAX_GENERATION_WAIT_MS;
  while (Date.now() < deadline) {
    const course = await Course.findById(courseId).select("lessons.status lessons.code lessons.totalFrames lessons.title");
    const lesson = course?.lessons?.[0];
    if (lesson?.status === "ready") return { courseId, lesson };
    if (lesson?.status === "failed") throw new Error(`Lesson 1 failed to generate for course ${courseId}.`);
    await sleep(POLL_INTERVAL_MS);
  }
  throw new Error(`Timed out after ${MAX_GENERATION_WAIT_MS / 1000}s waiting for course ${courseId}'s lesson 1.`);
}

// ── Stage 3: render to MP4, host it at a public URL ──────────────────────
// This is the server-side renderer (renderService.js — real headless-Chrome
// + ffmpeg, produces an actual file on disk), NOT the in-app "Download
// video" button (DownloadLessonButton.tsx), which runs entirely client-side
// via WebCodecs in a real browser tab and never touches the server at all
// — there is no server-side artifact from that path to grab. This is the
// same renderer server/scripts/renderLessonToMp4.js already uses as a CLI
// tool, just invoked here directly instead of from a terminal.
async function renderAndHost(postId, lesson) {
  const dir = path.join(UPLOADS_DIR, AUTOMATION_SUBDIR);
  fs.mkdirSync(dir, { recursive: true });
  const filename = `${postId}.mp4`;
  const outputPath = path.join(dir, filename);

  await renderLessonToFile({ code: lesson.code, totalFrames: lesson.totalFrames }, outputPath, () => {}, "landscape");

  const publicUrl = `${PUBLIC_BASE_URL}/uploads/${AUTOMATION_SUBDIR}/${filename}`;
  return { outputPath, publicUrl };
}

// Guards against a real failure mode: this file's video is saved to
// whatever disk THIS process is running on, but postVideoToTikTok() hands
// Buffer a URL built from PUBLIC_BASE_URL, which defaults to the live
// production backend (see the const above). Run this on a local/dev
// server without overriding PUBLIC_BASE_URL and the video sits on your
// laptop while Buffer tries to fetch it from production — which never got
// the file — and TikTok rejects the post with a generic "could not be
// read from its URL" only AFTER a full course generation + render has
// already run. Catching it here fails in ~0ms instead of ~5+ minutes.
function assertPublicUrlIsReachableFromHere() {
  const isProd = process.env.NODE_ENV === "production";
  const overridden = !!process.env.PUBLIC_BASE_URL;
  if (!isProd && !overridden) {
    throw new Error(
      "Refusing to run: this process is not NODE_ENV=production and PUBLIC_BASE_URL is not set, " +
      `so posted videos would be saved locally but advertised to Buffer/TikTok at the default ` +
      `production URL (${PUBLIC_BASE_URL}), which doesn't have the file. Either run this on the ` +
      "deployed production server, or set PUBLIC_BASE_URL to a tunnel (e.g. ngrok) that actually " +
      "exposes this machine's /uploads before testing locally."
    );
  }
}

// ── One full cycle ────────────────────────────────────────────────────────
async function runAutomationCycle() {
  const config = await getOrCreateAutomationConfig();
  if (!config.enabled) return { skipped: true, reason: "disabled" };

  let post;
  let localVideoPath = null;
  try {
    assertPublicUrlIsReachableFromHere();
    const owner = await getAutomationOwner();

    const { topic, caption } = await pickTopicAndCaption();
    post = await AutomationPost.create({ topic, caption, platforms: config.platforms, status: "generating" });
    console.log(`[automation] Starting cycle ${post._id}: "${topic}"`);

    const { courseId, lesson } = await generateAutomationCourse(topic, owner._id);
    post.courseId = courseId;
    post.status = "rendering";
    await post.save();

    const { outputPath, publicUrl } = await renderAndHost(post._id.toString(), lesson);
    localVideoPath = outputPath;
    post.status = "posting";
    await post.save();

    const result = await postVideoToTikTok(caption, publicUrl);
    post.status = "posted";
    post.bufferPostId = result.bufferPostId;
    post.postUrls = result.postUrl ? [{ platform: "tiktok", url: result.postUrl }] : [];
    await post.save();
    console.log(`[automation] ✓ Cycle ${post._id} posted to TikTok (buffer id: ${result.bufferPostId}).`);

    // Only delete on a CONFIRMED successful post — a failure anywhere above
    // leaves the file in place, so a failed cycle can still be inspected
    // instead of vanishing along with the only record it ever existed.
    fs.rmSync(localVideoPath, { force: true });
    post.videoDeletedAt = new Date();
    await post.save();

    return { success: true, postId: post._id };
  } catch (err) {
    console.error("[automation] Cycle failed:", err.message);
    if (post) {
      post.status = "failed";
      post.error = err.message;
      await post.save().catch(() => {});
    }
    return { success: false, error: err.message };
  } finally {
    await AutomationConfig.findOneAndUpdate({}, { lastRunAt: new Date() });
  }
}

// ── Scheduler ─────────────────────────────────────────────────────────────
// setTimeout chain, not a cron library — nothing here needs sub-minute
// precision or a cron expression, just "every N hours," and this way
// changing the frequency is just clearing/resetting one timer, no new
// dependency. nextRunAt is persisted so a server restart (routine on most
// hosts) resumes on schedule instead of silently going quiet.
let timer = null;

async function scheduleNext() {
  if (timer) clearTimeout(timer);
  const config = await getOrCreateAutomationConfig();
  if (!config.enabled) return;

  const delayMs = Math.max(config.frequencyHours * 60 * 60 * 1000, 60_000);
  const nextRunAt = new Date(Date.now() + delayMs);
  await AutomationConfig.findOneAndUpdate({}, { nextRunAt });

  timer = setTimeout(async () => {
    await runAutomationCycle();
    scheduleNext(); // always reschedule after a run, whether it succeeded or not
  }, delayMs);
  console.log(`[automation] Next cycle scheduled for ${nextRunAt.toISOString()}`);
}

// Called once at server boot (see server.js). If enabled and nextRunAt has
// already passed (server was down past it, or this is the very first run),
// fires soon rather than waiting a full frequencyHours from NOW — the
// point of persisting nextRunAt is that a restart doesn't quietly delay
// things by a whole extra cycle.
async function startAutomationScheduler() {
  const config = await getOrCreateAutomationConfig();
  if (!config.enabled) return;

  if (!config.nextRunAt || config.nextRunAt.getTime() <= Date.now()) {
    timer = setTimeout(async () => {
      await runAutomationCycle();
      scheduleNext();
    }, 30_000); // small delay, not instant — let the rest of server boot finish first
    console.log("[automation] Scheduler starting — first cycle in 30s (missed or first-ever run).");
  } else {
    const delayMs = config.nextRunAt.getTime() - Date.now();
    timer = setTimeout(async () => {
      await runAutomationCycle();
      scheduleNext();
    }, delayMs);
    console.log(`[automation] Scheduler resumed — next cycle at ${config.nextRunAt.toISOString()}`);
  }
}

// Called by the admin controller after enabled/frequency changes, and after
// a manual "run now" — always ends in a consistent single-timer state
// instead of two timers racing.
async function restartScheduler() {
  if (timer) { clearTimeout(timer); timer = null; }
  await scheduleNext();
}

function stopScheduler() {
  if (timer) { clearTimeout(timer); timer = null; }
}

// "Run now" from the admin page — fires a cycle immediately regardless of
// where the current timer is, then reschedules from THIS moment so the
// next automatic run doesn't land right on top of it (or seconds later
// against a stale nextRunAt from before this manual run).
async function runNow() {
  const resultPromise = runAutomationCycle();
  await restartScheduler();
  return resultPromise;
}

module.exports = {
  runAutomationCycle,
  startAutomationScheduler,
  restartScheduler,
  stopScheduler,
  runNow,
};
